#!/usr/bin/env python3
"""Regenerate INDEX.md from recipe frontmatter.

Reads every recipes/*.md (skipping files starting with _) and writes an index
grouped by tag, plus a flat A-Z list. Deliberately dependency-free so it runs
anywhere, including a fresh phone session.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECIPES = ROOT / "recipes"
INDEX = ROOT / "INDEX.md"


def parse_frontmatter(text):
    """Return a dict of top-level `key: value` pairs from a leading --- block."""
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    meta = {}
    for line in text[3:end].splitlines():
        if not line.strip() or line.startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta


def parse_tags(raw):
    if not raw:
        return []
    raw = raw.strip().strip("[]")
    return [t.strip().strip("'\"") for t in raw.split(",") if t.strip()]


def main():
    recipes = []
    for path in sorted(RECIPES.glob("*.md")):
        if path.name.startswith("_"):
            continue
        meta = parse_frontmatter(path.read_text(encoding="utf-8"))
        title = meta.get("title") or path.stem.replace("-", " ").title()
        recipes.append(
            {
                "title": title,
                "path": f"recipes/{path.name}",
                "tags": parse_tags(meta.get("tags")),
                "servings": meta.get("servings", ""),
                "total_time": meta.get("total_time", ""),
            }
        )

    lines = ["# Index", "", f"{len(recipes)} recipes. Generated by `bin/reindex.py` — do not hand-edit.", ""]

    by_tag = defaultdict(list)
    for r in recipes:
        for tag in r["tags"] or ["untagged"]:
            by_tag[tag].append(r)

    if by_tag:
        lines += ["## By tag", ""]
        for tag in sorted(by_tag):
            titles = ", ".join(
                f"[{r['title']}]({r['path']})" for r in sorted(by_tag[tag], key=lambda r: r["title"].lower())
            )
            lines.append(f"- **{tag}** — {titles}")
        lines.append("")

    lines += ["## All recipes", "", "| Recipe | Tags | Serves | Time |", "| --- | --- | --- | --- |"]
    for r in sorted(recipes, key=lambda r: r["title"].lower()):
        lines.append(
            f"| [{r['title']}]({r['path']}) | {', '.join(r['tags'])} | {r['servings']} | {r['total_time']} |"
        )
    lines.append("")

    INDEX.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(recipes)} recipes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
